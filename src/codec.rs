/// Domain separator used when hashing admin proposals.
pub const ADMIN_PROPOSAL_HASH_DOMAIN: &[u8] = b"PROOF_ADMIN_PROPOSAL_V1";

/// Encodes an admin action into the canonical MessagePack form used for
/// storage, hashing, and equality checks.
pub fn canonical_admin_action_bytes(action: &AdminAction) -> Result<Vec<u8>, ExecError> {
    rmp_serde::to_vec(action).map_err(|e| ExecError::InternalError(e.to_string()))
}

/// Decodes an admin action and returns it with its canonical MessagePack bytes.
/// Unknown action variants fail decoding.
pub fn canonicalize_admin_action(bytes: &[u8]) -> Result<(AdminAction, Vec<u8>), ExecError> {
    let action: AdminAction =
        rmp_serde::from_slice(bytes).map_err(|e| ExecError::DecodeError(e.to_string()))?;
    let canonical = canonical_admin_action_bytes(&action)?;
    Ok((action, canonical))
}

/// Computes the domain-separated commitment for an admin proposal.
///
/// ```text
/// sha256( "PROOF_ADMIN_PROPOSAL_V1" || chain_id(32) || proposal_id(8 BE) ||
///         registry_version(8 BE) || threshold(4 BE) || proposer(20) ||
///         created_height(8 BE) || created_ms(8 BE) || expiry_ms(8 BE) ||
///         action_tag(1) || len(action_bytes)(4 BE) || action_bytes )
/// ```
///
/// The engine derives the action tag and canonical action bytes from the typed
/// action. The chain identifier prevents cross-chain reuse, and the length
/// prefix prevents concatenation ambiguity.
///
/// Returns [`ExecError::Overflow`] if the canonical action length exceeds
/// `u32::MAX`.
#[allow(clippy::too_many_arguments)]
pub fn admin_proposal_content_hash(
    chain_id: &[u8; 32],
    proposal_id: ProposalId,
    registry_version: RegistryVersion,
    threshold: SignatureThreshold,
    proposer: &SignerAddress,
    created_height: u64,
    created_ms: u64,
    expiry_ms: u64,
    action: &AdminAction,
) -> Result<[u8; 32], ExecError> {
    use sha2::{Digest, Sha256};
    let action_bytes = canonical_admin_action_bytes(action)?;
    let len = u32::try_from(action_bytes.len()).map_err(|_| ExecError::Overflow)?;
    let mut h = Sha256::new();
    h.update(ADMIN_PROPOSAL_HASH_DOMAIN);
    h.update(chain_id);
    h.update(proposal_id.0.to_be_bytes());
    h.update(registry_version.0.to_be_bytes());
    h.update(threshold.0.to_be_bytes());
    h.update(proposer.0);
    h.update(created_height.to_be_bytes());
    h.update(created_ms.to_be_bytes());
    h.update(expiry_ms.to_be_bytes());
    h.update([action.action_tag()]);
    h.update(len.to_be_bytes());
    h.update(&action_bytes);
    Ok(h.finalize().into())
}

/// Byte buffer that always serializes as msgpack `bin` (0xc4/c5/c6),
/// never as msgpack `array` (0xdc/0xdd). Used in `WireTxEnvelope` fields
/// that must match the Go CheckTx parser's wire format.
#[derive(Clone, Debug)]
struct WireBlob(Vec<u8>);

impl Serialize for WireBlob {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        serde_bytes::Bytes::new(&self.0).serialize(s)
    }
}

impl<'de> Deserialize<'de> for WireBlob {
    fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        serde_bytes::ByteBuf::deserialize(d).map(|b| WireBlob(b.into_vec()))
    }
}

#[cfg(test)]
impl WireBlob {
    fn from_test_payload(bytes: Vec<u8>) -> Self {
        WireBlob(bytes)
    }
}

impl std::ops::Deref for WireBlob {
    type Target = Vec<u8>;

    fn deref(&self) -> &Vec<u8> {
        &self.0
    }
}

/// Envelope version emitted by this build.
pub const ENVELOPE_VERSION: u8 = 2;

/// Wire envelope versions this build accepts on decode. Single source of
/// truth — mirrored by `supportedEnvelopeVersions` in
/// `exchange-node/check_tx.go` and the SDK check in `sdk/src/codec.ts`.
/// Add a new version here when introducing one; drop an old one when it
/// is no longer permitted. Decoders MUST consult this slice instead of
/// hardcoding numeric comparisons.
pub const SUPPORTED_ENVELOPE_VERSIONS: &[u8] = &[ENVELOPE_VERSION];

/// Largest canonical unsigned `LiquidateAccounts` transaction admitted by
/// schema-v9 proposal policy. The payload maximum is 11,012 bytes for 256
/// owners whose 20 address bytes all require MessagePack `uint8`; the fixed
/// envelope contributes 107 bytes (fixarray/version/tag/seq, bin16 payload
/// header, bin8 pubkey, and bin8 signature).
pub const MAX_LIQUIDATE_ACCOUNTS_TX_BYTES: usize = 11_119;

/// Wire envelope: `[version=2, action_type, seq, payload_bytes, pubkey, signature]`.
///
/// Byte fields use [`WireBlob`] which enforces msgpack `bin` encoding at the
/// type level (not just an annotation). The Go CheckTx parser
/// (exchange-node/check_tx.go) and the SDK both expect this shape.
///
/// The `version` byte stays `2` and the signing-prefix string stays
/// `"ProofExchange-v2"` because every existing signature in dev/devnet
/// was produced under that prefix. The legacy unsigned (v1) envelope
/// was removed pre-launch.
#[derive(Serialize, Deserialize)]
pub struct WireTxEnvelope {
    version: u8,
    action_type: u8,
    seq: u64,
    payload: WireBlob,
    #[serde(with = "serde_bytes")]
    pubkey: [u8; 32],
    #[serde(with = "serde_bytes")]
    signature: [u8; 64],
}

impl WireTxEnvelope {
    /// The wire discriminant this envelope carries. Available after envelope
    /// decode, before the payload has been interpreted — the seam consensus
    /// gates that must be indistinguishable from a pre-upgrade binary's
    /// unknown-action failure hook into.
    pub fn action_type(&self) -> u8 {
        self.action_type
    }
}

/// Authentication data extracted from the wire envelope.
#[derive(Debug)]
pub struct TxAuth {
    pub pubkey: [u8; 32],
    pub signature: [u8; 64],
    pub action_type: u8,
    pub payload: Vec<u8>,
}

/// Result of decoding a transaction.
#[derive(Debug)]
pub struct DecodedTx {
    pub action: Action,
    pub seq: u64,
    pub auth: TxAuth,
}

/// Decode raw tx bytes as a signed wire envelope:
/// fixarray(6) `[version=2, action_type, seq, payload, pubkey, signature]`.
pub fn decode_tx(bytes: &[u8]) -> Result<DecodedTx, ExecError> {
    decode_tx_from_envelope(decode_envelope(bytes)?)
}

/// Stage 1 of [`decode_tx`]: the outer wire envelope (structure, field
/// lengths, version) with the payload still uninterpreted. Split out so the
/// engine can gate an action_type on consensus state *between* envelope and
/// payload decode — reproducing exactly what a binary without that
/// action_type produces, for well-formed and malformed payloads alike.
pub fn decode_envelope(bytes: &[u8]) -> Result<WireTxEnvelope, ExecError> {
    if bytes.is_empty() {
        return Err(ExecError::DecodeError("empty tx".to_string()));
    }

    let envelope: WireTxEnvelope =
        rmp_serde::from_slice(bytes).map_err(|e| ExecError::DecodeError(e.to_string()))?;

    if !SUPPORTED_ENVELOPE_VERSIONS.contains(&envelope.version) {
        return Err(ExecError::DecodeError(format!(
            "unsupported envelope version: {} (supported: {:?})",
            envelope.version, SUPPORTED_ENVELOPE_VERSIONS
        )));
    }

    Ok(envelope)
}

/// Stage 2 of [`decode_tx`]: interpret the payload under the envelope's
/// action_type.
pub fn decode_tx_from_envelope(envelope: WireTxEnvelope) -> Result<DecodedTx, ExecError> {
    let action = decode_action(envelope.action_type, &envelope.payload)?;

    Ok(DecodedTx {
        action,
        seq: envelope.seq,
        auth: TxAuth {
            pubkey: envelope.pubkey,
            signature: envelope.signature,
            action_type: envelope.action_type,
            payload: envelope.payload.0,
        },
    })
}

/// Encode an action with a pre-computed pubkey + signature into a wire envelope.
/// Most callers should use [`sign_and_encode_with_chain`] instead; this exists for paths
/// (api-gateway forward, FFI relays) that already hold raw signature bytes.
pub fn encode_signed_tx(
    action: &Action,
    seq: u64,
    pubkey: &[u8; 32],
    signature: &[u8; 64],
) -> Result<Vec<u8>, ExecError> {
    let EncodedAction {
        action_type,
        payload,
    } = action.encode_action()?;
    let envelope = WireTxEnvelope {
        version: ENVELOPE_VERSION,
        action_type,
        seq,
        payload,
        pubkey: *pubkey,
        signature: *signature,
    };
    rmp_serde::to_vec(&envelope).map_err(|e| ExecError::InternalError(e.to_string()))
}

/// Encode the proposer-injected internal `LiquidateAccounts` action in its
/// canonical unsigned form: zeroed pubkey + signature, `seq = 0`. The only
/// legitimate producer is the validator's own PrepareProposal hook (via the
/// FFI candidates export) — CheckTx rejects action type 0x1D so these bytes
/// can never enter the mempool, and `execute_tx` rejects any non-canonical
/// (non-zeroed) variant.
pub fn encode_liquidate_accounts_tx(owners: Vec<[u8; 20]>) -> Result<Vec<u8>, ExecError> {
    if owners.len() > crate::types::MAX_LIQUIDATE_ACCOUNTS_OWNERS {
        return Err(ExecError::DecodeError(format!(
            "LiquidateAccounts owner count {} exceeds maximum {}",
            owners.len(),
            crate::types::MAX_LIQUIDATE_ACCOUNTS_OWNERS
        )));
    }
    if owners.windows(2).any(|pair| pair[0] >= pair[1]) {
        return Err(ExecError::DecodeError(
            "LiquidateAccounts owners must be strictly sorted and unique".to_string(),
        ));
    }
    encode_signed_tx(
        &Action::LiquidateAccounts(crate::types::LiquidateAccounts { owners }),
        0,
        &[0u8; 32],
        &[0u8; 64],
    )
}

/// Sign an action and encode it as a wire envelope, binding the
/// signature to a specific `chain_id`. The signing bytes carry a 32-byte
/// chain_id prefix per audit B4 — `chain_id` is established by
/// genesis / snapshot-load, not carried on the wire.
pub fn sign_and_encode_with_chain(
    chain_id: &[u8; 32],
    action: &Action,
    seq: u64,
    signing_key: &ed25519_dalek::SigningKey,
) -> Result<Vec<u8>, ExecError> {
    use ed25519_dalek::Signer;

    let EncodedAction {
        action_type,
        payload,
    } = action.encode_action()?;
    let msg = crate::crypto::signing_message(chain_id, action_type, seq, &payload);
    let sig = signing_key.sign(&msg);

    let pubkey = signing_key.verifying_key().to_bytes();
    let signature = sig.to_bytes();

    let envelope = WireTxEnvelope {
        version: ENVELOPE_VERSION,
        action_type,
        seq,
        payload,
        pubkey,
        signature,
    };
    rmp_serde::to_vec(&envelope).map_err(|e| ExecError::InternalError(e.to_string()))
}

/// Sign and encode from a raw `action_type` + already-serialized `payload`,
/// bypassing the typed `Action` enum. Lets conformance/vector generators and
/// bindings sign arbitrary (action_type, payload) pairs through the one codec.
pub fn sign_and_encode_payload(
    chain_id: &[u8; 32],
    action_type: u8,
    payload: &[u8],
    seq: u64,
    signing_key: &ed25519_dalek::SigningKey,
) -> Result<Vec<u8>, ExecError> {
    use ed25519_dalek::Signer;

    let msg = crate::crypto::signing_message(chain_id, action_type, seq, payload);
    let sig = signing_key.sign(&msg);
    let pubkey = signing_key.verifying_key().to_bytes();
    let signature = sig.to_bytes();

    let envelope = WireTxEnvelope {
        version: ENVELOPE_VERSION,
        action_type,
        seq,
        payload: WireBlob(payload.to_vec()),
        pubkey,
        signature,
    };
    rmp_serde::to_vec(&envelope).map_err(|e| ExecError::InternalError(e.to_string()))
}

/// Decoded wire envelope components (raw, no `Action` enum) — for bindings and
/// tools that want the fields without constructing the typed action.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DecodedTxRaw {
    pub version: u8,
    pub action_type: u8,
    pub seq: u64,
    pub payload: Vec<u8>,
    pub pubkey: [u8; 32],
    pub signature: [u8; 64],
}

/// Encode a signed tx from raw parts (action_type, payload, pubkey, signature)
/// without the typed `Action` — the inverse-input of [`decode_tx_raw`].
pub fn encode_signed_tx_raw(
    action_type: u8,
    payload: &[u8],
    seq: u64,
    pubkey: &[u8; 32],
    signature: &[u8; 64],
) -> Result<Vec<u8>, ExecError> {
    let envelope = WireTxEnvelope {
        version: ENVELOPE_VERSION,
        action_type,
        seq,
        payload: WireBlob(payload.to_vec()),
        pubkey: *pubkey,
        signature: *signature,
    };
    rmp_serde::to_vec(&envelope).map_err(|e| ExecError::InternalError(e.to_string()))
}

/// Decode a wire tx into its raw envelope components without decoding the
/// payload into a typed `Action`.
pub fn decode_tx_raw(bytes: &[u8]) -> Result<DecodedTxRaw, ExecError> {
    if bytes.is_empty() {
        return Err(ExecError::DecodeError("empty tx".to_string()));
    }
    let envelope: WireTxEnvelope =
        rmp_serde::from_slice(bytes).map_err(|e| ExecError::DecodeError(e.to_string()))?;
    if !SUPPORTED_ENVELOPE_VERSIONS.contains(&envelope.version) {
        return Err(ExecError::DecodeError(format!(
            "unsupported envelope version: {} (supported: {:?})",
            envelope.version, SUPPORTED_ENVELOPE_VERSIONS
        )));
    }
    Ok(DecodedTxRaw {
        version: envelope.version,
        action_type: envelope.action_type,
        seq: envelope.seq,
        payload: envelope.payload.0,
        pubkey: envelope.pubkey,
        signature: envelope.signature,
    })
}

/// Extract the action_type byte from a wire tx without full decoding.
pub fn peek_action_type(bytes: &[u8]) -> Option<u8> {
    rmp_serde::from_slice::<WireTxEnvelope>(bytes)
        .ok()
        .map(|env| env.action_type)
}

/// Read only the version and action tag from the admitted six-field fixarray
/// envelope. This performs no allocation and never touches the payload. It is
/// intentionally only a cheap pre-classifier; exact Tier-2 canonicality still
/// comes from [`canonical_tier2_action_type`].
pub fn peek_fixarray_action_type(bytes: &[u8]) -> Option<u8> {
    if bytes.first().copied()? != 0x96 {
        return None;
    }
    let (version, version_len) = read_msgpack_uint_prefix(bytes.get(1..)?)?;
    let version = u8::try_from(version).ok()?;
    if !SUPPORTED_ENVELOPE_VERSIONS.contains(&version) {
        return None;
    }
    let action_offset = 1usize.checked_add(version_len)?;
    let (action_type, _) = read_msgpack_uint_prefix(bytes.get(action_offset..)?)?;
    u8::try_from(action_type).ok()
}

fn read_msgpack_uint_prefix(bytes: &[u8]) -> Option<(u64, usize)> {
    let lead = *bytes.first()?;
    match lead {
        0x00..=0x7f => Some((u64::from(lead), 1)),
        0xcc => Some((u64::from(*bytes.get(1)?), 2)),
        0xcd => Some((
            u64::from(u16::from_be_bytes([*bytes.get(1)?, *bytes.get(2)?])),
            3,
        )),
        0xce => Some((
            u64::from(u32::from_be_bytes([
                *bytes.get(1)?,
                *bytes.get(2)?,
                *bytes.get(3)?,
                *bytes.get(4)?,
            ])),
            5,
        )),
        0xcf => Some((
            u64::from_be_bytes([
                *bytes.get(1)?,
                *bytes.get(2)?,
                *bytes.get(3)?,
                *bytes.get(4)?,
                *bytes.get(5)?,
                *bytes.get(6)?,
                *bytes.get(7)?,
                *bytes.get(8)?,
            ]),
            9,
        )),
        _ => None,
    }
}

/// Return the semantic action type only when `bytes` are the exact canonical
/// envelope and payload this build emits. This closes the gap between the
/// deliberately lightweight Go proposal parser and serde's acceptance of
/// alternate MessagePack integer/container encodings.
pub fn canonical_action_type(bytes: &[u8]) -> Option<ActionType> {
    let raw_action_type = peek_fixarray_action_type(bytes)?;
    let action_type = ActionType::try_from(raw_action_type).ok()?;
    let decoded = decode_tx(bytes).ok()?;
    let canonical = match &decoded.action {
        Action::LiquidateAccounts(cmd) => encode_liquidate_accounts_tx(cmd.owners.clone()).ok()?,
        _ => encode_signed_tx(
            &decoded.action,
            decoded.seq,
            &decoded.auth.pubkey,
            &decoded.auth.signature,
        )
        .ok()?,
    };
    (canonical == bytes).then_some(action_type)
}

/// Return the trigger-era block phase only for exact canonical transaction
/// bytes. Both ProcessProposal and FinalizeBlock use this result; malformed or
/// alternate envelopes fail closed instead of being placed in an implicit
/// catch-all phase.
pub fn canonical_block_phase(bytes: &[u8]) -> Option<BlockPhase> {
    canonical_action_type(bytes).map(action_block_phase)
}

/// Return the semantic Tier-2 action type only when `bytes` are the exact
/// canonical envelope this build emits. Proposal admission uses a lightweight
/// Go parser, but FinalizeBlock repeats the rule in Rust so alternate
/// MessagePack struct representations accepted by serde cannot bypass the
/// block-work counter.
pub fn canonical_tier2_action_type(bytes: &[u8]) -> Option<ActionType> {
    let action_type = ActionType::try_from(peek_fixarray_action_type(bytes)?).ok()?;
    // Must stay the same set the node's block proposer classifies as Tier-2.
    // A resolution missing here is admitted by the proposer as the block's one
    // Tier-2 action and then not counted by the engine at finalize, which goes
    // on to spend the automatic resolution allowance in the same block.
    if !matches!(
        action_type,
        ActionType::ResolveImpactMarket
            | ActionType::ResolveEvent
            | ActionType::RunLiquidationSweep
            | ActionType::LiquidateAccounts
    ) {
        return None;
    }
    (canonical_action_type(bytes)? == action_type).then_some(action_type)
}

/// Extract the seq number from a wire tx without deserializing the payload action.
/// The payload bytes are read but not interpreted.
pub fn peek_seq(bytes: &[u8]) -> Option<u64> {
    let envelope: WireTxEnvelope = rmp_serde::from_slice(bytes).ok()?;
    Some(envelope.seq)
}

