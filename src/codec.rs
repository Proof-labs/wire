/// State-independent transaction phase enforced once position triggers are
/// active. Numeric values are consensus-facing golden-table entries shared
/// with the Go proposer; changing a membership or ordering is a coordinated
/// protocol change.
#[repr(u8)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum BlockPhase {
    PriceCreditPrefix = 0,
    AgentAuthority = 1,
    BoundedLiquidation = 2,
    TriggerManagement = 3,
    Ordinary = 4,
}

/// Classify one semantic action into the approved trigger-era block spine.
/// Scheduled trigger-configuration transitions, mark freezing, and the
/// trigger sweep are internal Rust phases and therefore have no wire action.
pub const fn action_block_phase(action_type: ActionType) -> BlockPhase {
    match action_type {
        ActionType::OracleUpdate
        | ActionType::SubmitOracleObservation
        | ActionType::OracleUpdateComposite
        | ActionType::Deposit
        | ActionType::ConfirmDeposit
        | ActionType::FailWithdrawal
        // W28-20 receipt-gated terminals replace the legacy relayer
        // Confirm/FailWithdrawal and take the same credit-band phase.
        | ActionType::ConfirmWithdrawalReceipt
        | ActionType::FailWithdrawalReceipt
        | ActionType::AuthorizeWithdrawal => BlockPhase::PriceCreditPrefix,
        ActionType::ApproveAgent | ActionType::RevokeAgent => BlockPhase::AgentAuthority,
        ActionType::LiquidateAccounts => BlockPhase::BoundedLiquidation,
        ActionType::CancelOrder
        | ActionType::CancelClientOrder
        | ActionType::CancelAllOrders
        | ActionType::SetPositionTriggers
        | ActionType::CancelPositionTriggers => BlockPhase::TriggerManagement,
        ActionType::PlaceOrder
        | ActionType::MarketOrder
        | ActionType::Withdraw
        | ActionType::CreateMarket
        | ActionType::WithdrawRequest
        | ActionType::ConfirmWithdrawal
        | ActionType::CreateImpactMarket
        | ActionType::ResolveImpactMarket
        | ActionType::ResolveEvent
        | ActionType::UpdateMarketFees
        | ActionType::RunLiquidationSweep
        | ActionType::RunFundingTick
        | ActionType::SetAccountFeeOverride
        | ActionType::FailDeposit
        | ActionType::SetUserMarketLeverage
        | ActionType::ClosePosition
        | ActionType::CancelReplaceOrder
        | ActionType::AmendOrder
        | ActionType::AtomicBasketOrder
        | ActionType::ProposeAdminAction
        | ActionType::ApproveAdminAction
        | ActionType::RejectAdminAction
        | ActionType::EmergencyAdminAction
        | ActionType::CreateSubAccount
        | ActionType::SubAccountTransfer => BlockPhase::Ordinary,
    }
}

