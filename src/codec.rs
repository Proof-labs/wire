    #[test]
    fn oi_cap_tail_fields_accept_legacy_payloads_but_require_a_major_release() {
        // Frozen 11-field CreateMarket bytes decode under the new action.
        let old_create = pre_oi_create_market();
        let old_create_bytes = rmp_serde::to_vec(&old_create).unwrap();
        let decoded: CreateMarket = rmp_serde::from_slice(&old_create_bytes).unwrap();
        assert_eq!(decoded.market, old_create.market);
        assert_eq!(decoded.ticker, old_create.ticker);
        assert_eq!(decoded.max_open_interest, 0);

        // The v2 serializer is LENGTH-STABLE: a zero cap and a non-zero cap
        // both encode as a 12-element array, differing only in the tail value.
        // This is the property to defend. A serializer that dropped the zero
        // tail would buy byte-identity with v1 at the cost of making the array
        // length depend on the field's value — and in a positional layout that
        // means a future 13th field would be silently shifted into slot 11
        // whenever the cap happened to be zero. Pin the msgpack fixarray
        // header (0x90 | n) so a regression is caught at the byte level.
        let with_cap = |max_open_interest| CreateMarket {
            market: old_create.market,
            im_bps: old_create.im_bps,
            mm_bps: old_create.mm_bps,
            taker_fee_bps: old_create.taker_fee_bps,
            maker_fee_bps: old_create.maker_fee_bps,
            signer: old_create.signer,
            funding_interval_ms: old_create.funding_interval_ms,
            max_funding_rate_bps: old_create.max_funding_rate_bps,
            pool_id: old_create.pool_id,
            sz_decimals: old_create.sz_decimals,
            ticker: old_create.ticker.clone(),
            max_open_interest,
        };
        let uncapped_bytes = rmp_serde::to_vec(&with_cap(0)).unwrap();
        let capped_bytes = rmp_serde::to_vec(&with_cap(77)).unwrap();
        assert_eq!(
            old_create_bytes[0], 0x9b,
            "frozen v1 CreateMarket must be an 11-element array"
        );
        assert_eq!(
            uncapped_bytes[0], 0x9c,
            "v2 zero-cap CreateMarket must still be a 12-element array"
        );
        assert_eq!(
            capped_bytes[0], 0x9c,
            "v2 capped CreateMarket must be a 12-element array"
        );

        // The v2 uncapped body is the frozen v1 body plus an explicit `0` tail
        // (msgpack positive fixint 0x00) — a pure append, which is what keeps
        // legacy payloads decodable while the length stays value-independent.
        assert_eq!(
            uncapped_bytes[1..].to_vec(),
            [&old_create_bytes[1..], &[0x00u8][..]].concat()
        );

        // A frozen 11-field decoder rejects BOTH v2 sequences — capped and
        // uncapped alike. MessagePack positional structs require an exact array
        // length, so no v2 CreateMarket is forward-decodable by v1 and this wire
        // change is MAJOR. (Under a zero-skipping serializer the uncapped form
        // would have survived here; giving that up is the deliberate trade.)
        for (label, bytes) in [("uncapped", &uncapped_bytes), ("capped", &capped_bytes)] {
            let error = rmp_serde::from_slice::<PreOiCreateMarket>(bytes).unwrap_err();
            assert!(
                error.to_string().contains("length")
                    || error.to_string().contains("LengthMismatch"),
                "unexpected frozen CreateMarket decoder error ({label}): {error}"
            );
        }

        // Repeat both directions for UpdateMarketFees: the released v1 shape
        // already carried the IM/MM tails (20 fields); v2 appends only max OI.
        let old_update = pre_oi_update_market_fees();
        let old_update_bytes = rmp_serde::to_vec(&old_update).unwrap();
        let decoded: UpdateMarketFees = rmp_serde::from_slice(&old_update_bytes).unwrap();
        assert_eq!(decoded.market, old_update.market);
        assert_eq!(decoded.tick_size, old_update.tick_size);
        assert_eq!(decoded.im_bps, old_update.im_bps);
        assert_eq!(decoded.mm_bps, old_update.mm_bps);
        assert_eq!(decoded.max_open_interest, None);

        let new_update = UpdateMarketFees {
            market: old_update.market,
            signer: old_update.signer,
            taker_fee_bps: old_update.taker_fee_bps,
            maker_fee_bps: old_update.maker_fee_bps,
            max_funding_rate_bps: old_update.max_funding_rate_bps,
            funding_interval_ms: old_update.funding_interval_ms,
            max_position_size: old_update.max_position_size,
            default_ttl_ms: old_update.default_ttl_ms,
            net_delta_margin: old_update.net_delta_margin,
            tick_size: old_update.tick_size,
            lot_size: old_update.lot_size,
            primary_oracle_signer: old_update.primary_oracle_signer,
            oracle_staleness_ms: old_update.oracle_staleness_ms,
            mark_source_mode: old_update.mark_source_mode,
            max_mark_spread_bps: old_update.max_mark_spread_bps,
            cex_composite_staleness_ms: old_update.cex_composite_staleness_ms,
            partial_liquidation_enabled: old_update.partial_liquidation_enabled,
            fee_tiers: old_update.fee_tiers.clone(),
            im_bps: old_update.im_bps,
            mm_bps: old_update.mm_bps,
            max_open_interest: Some(99),
        };
        let error = rmp_serde::from_slice::<PreOiUpdateMarketFees>(
            &rmp_serde::to_vec(&new_update).unwrap(),
        )
        .unwrap_err();
        assert!(
            error.to_string().contains("length") || error.to_string().contains("LengthMismatch"),
            "unexpected frozen UpdateMarketFees decoder error: {error}"
        );
    }

